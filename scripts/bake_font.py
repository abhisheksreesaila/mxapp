"""Bake Noto Sans (SIL Open Font License) into glyph atlases for text drawn on canvases.

  pixi run python scripts/bake_font.py        # writes mojoui/font_data.mojo

Three faces: Regular and Medium at 26 px for labels, Medium at 64 px (digits and money
signs only) for big numbers. Each atlas is 8-bit coverage, base64 in a Mojo string, with a
table of glyph boxes and advances. mojoui/text.mojo samples them at any size.
"""

import base64
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = Path("/usr/share/fonts/noto")
TEXT = "".join(chr(c) for c in range(32, 127)) + "·×–—…€£°▲▼"
DIGITS = "0123456789$€£.,%+-−KMBk "
MONO_DIR = Path("/usr/share/fonts/TTF")  # JetBrains Mono (SIL Open Font License 1.1), the Omarchy look
FACES = [("REGULAR", "NotoSans-Regular.ttf", 26, TEXT), ("MEDIUM", "NotoSans-Medium.ttf", 26, TEXT),
         ("DISPLAY", "NotoSans-Medium.ttf", 64, DIGITS),
         ("MONO", MONO_DIR / "JetBrainsMonoNerdFont-Regular.ttf", 26, TEXT),
         ("MONO_BOLD", MONO_DIR / "JetBrainsMonoNerdFont-Bold.ttf", 26, TEXT)]
WIDTH = 1024


def bake(file, size, chars):
    path = file if isinstance(file, Path) else FONTS / file
    font = ImageFont.truetype(str(path), size)
    design = ImageFont.truetype(str(path), 1000)  # unhinted advances, exact at any size
    ascent, descent = font.getmetrics()
    glyphs, x, y, row_h = [], 1, 1, 0
    boxes = []
    for ch in chars:
        l, t, r, b = font.getbbox(ch, anchor="ls")  # relative to the baseline origin
        w, h = max(r - l, 0), max(b - t, 0)
        if x + w + 2 > WIDTH:
            x, y, row_h = 1, y + row_h + 2, 0
        boxes.append((ch, x, y, w, h, l, t, design.getlength(ch) * size / 1000))
        x += w + 2
        row_h = max(row_h, h)
    height = y + row_h + 2
    atlas = Image.new("L", (WIDTH, height), 0)
    draw = ImageDraw.Draw(atlas)
    for ch, gx, gy, w, h, l, t, adv in boxes:
        if w and h:
            draw.text((gx - l, gy - t), ch, font=font, fill=255, anchor="ls")
        glyphs.append(f"{ord(ch)},{gx},{gy},{w},{h},{l},{t},{round(adv * 64)}")
    return dict(size=size, ascent=ascent, descent=descent, width=WIDTH, height=height,
                table=";".join(glyphs), atlas=base64.b64encode(atlas.tobytes()).decode())


def main():
    out = ["# Generated by scripts/bake_font.py from Noto Sans and JetBrains Mono (SIL Open Font License 1.1). Don't edit.",
           "# Each face: pixel size, ascent, descent, atlas width/height, glyph table",
           "# (codepoint,x,y,w,h,left,top,advance×64 per glyph, ';'-separated), atlas coverage in base64.", ""]
    for name, file, size, chars in FACES:
        f = bake(file, size, chars)
        out.append(f"comptime {name}_SIZE = {f['size']}")
        out.append(f"comptime {name}_ASCENT = {f['ascent']}")
        out.append(f"comptime {name}_DESCENT = {f['descent']}")
        out.append(f"comptime {name}_WIDTH = {f['width']}")
        out.append(f"comptime {name}_HEIGHT = {f['height']}")
        out.append(f'comptime {name}_TABLE = "{f["table"]}"')
        out.append(f'comptime {name}_ATLAS = "{f["atlas"]}"')
        out.append("")
    path = ROOT / "mojoui" / "font_data.mojo"
    path.write_text("\n".join(out))
    print(f"{path}: {path.stat().st_size // 1024} KB")


if __name__ == "__main__":
    sys.exit(main())
